import { describe, expect, it } from 'vitest'
import { createLiveStore } from '../src/stores/live'
import { createSettingsStore } from '../src/stores/settings'

function makeLive() {
  const settings = createSettingsStore(null)
  const live = createLiveStore(settings)
  return { settings, live }
}

describe('live store — card entry', () => {
  it('walks P→B→P slots and advises surrender on hard 16 vs a ten', () => {
    const { live } = makeLive()
    expect(live.turnStyle.value).toBe('p-b-p')
    expect(live.canUndo.value).toBe(false)
    expect(live.nextNeeded.value).toBe('mine')
    live.pick('T')
    expect(live.canUndo.value).toBe(true)
    expect(live.nextNeeded.value).toBe('up')
    live.pick('T')
    expect(live.nextNeeded.value).toBe('mine')
    live.pick('6')
    expect(live.nextNeeded.value).toBe('none')
    expect(live.activeCards.value).toEqual(['T', '6'])
    expect(live.dealer.value).toBe('T')
    expect(live.handState.value).toBe('playing')
    expect(live.advice.value?.action).toBe('surrender')
  })

  it('walks P→P→B slots to the same play', () => {
    const { settings, live } = makeLive()
    settings.updateLive({ turnStyle: 'p-p-b' })
    expect(live.turnStyle.value).toBe('p-p-b')
    expect(live.nextNeeded.value).toBe('mine')
    live.pick('T')
    expect(live.nextNeeded.value).toBe('mine')
    live.pick('6')
    expect(live.nextNeeded.value).toBe('up')
    live.pick('T')
    expect(live.nextNeeded.value).toBe('none')
    expect(live.activeCards.value).toEqual(['T', '6'])
    expect(live.dealer.value).toBe('T')
    expect(live.advice.value?.action).toBe('surrender')
  })

  it('stays in entry state until the hand and upcard are complete', () => {
    const { settings, live } = makeLive()
    live.pick('T')
    expect(live.handState.value).toBe('entry')
    expect(live.advice.value).toBeNull()
    live.pick('7')
    expect(live.handState.value).toBe('entry')
    live.pick('6')
    expect(live.handState.value).toBe('playing')
    expect(live.advice.value?.action).toBe('hit')
    // player-first tables can complete the hand before the upcard arrives
    settings.updateLive({ turnStyle: 'p-p-b' })
    live.newRound()
    live.pick('T')
    live.pick('6')
    expect(live.handState.value).toBe('entry')
    expect(live.nextNeeded.value).toBe('up')
  })

  it('re-derives advice on follow-up cards, finishes 21s and busts on their own', () => {
    const { live } = makeLive()
    live.pick('T')
    live.pick('9')
    live.pick('5')
    expect(live.advice.value?.action).toBe('hit')
    live.pick('7')
    // 22 — the last hand busts straight into the round-over state
    expect(live.roundDone.value).toBe(true)
    expect(live.handState.value).toBe('roundDone')
    expect(live.advice.value).toBeNull()
    expect(live.nextNeeded.value).toBe('none')
    expect(live.canUndo.value).toBe(true)
    // taps are ignored once the round is over
    live.pick('2')
    expect(live.activeCards.value).toEqual(['T', '5', '7'])
    expect(live.seen.value).toEqual(['T', '9', '5', '7'])
    // undo reopens the round; the bust state is visible again
    live.undo()
    expect(live.roundDone.value).toBe(false)
    expect(live.handState.value).toBe('bust')
    expect(live.advice.value).toBeNull()
    live.undo()
    expect(live.activeCards.value).toEqual(['T', '5'])
    expect(live.advice.value?.action).toBe('hit')
  })

  it('finishes a twenty-one on its own', () => {
    const { live } = makeLive()
    live.pick('T')
    live.pick('4')
    live.pick('7')
    expect(live.handState.value).toBe('playing')
    live.pick('4')
    expect(live.roundDone.value).toBe(true)
    live.undo()
    expect(live.handState.value).toBe('twentyone')
    expect(live.advice.value).toBeNull()
  })

  it('advice follows live rule changes', () => {
    const { settings, live } = makeLive()
    live.pick('T')
    live.pick('T')
    live.pick('6')
    expect(live.advice.value?.action).toBe('surrender')
    settings.updateRules({ peek: false })
    // ENHC: late surrender disappears, hard 16 falls back to hit
    expect(live.advice.value?.action).toBe('hit')
  })
})

describe('live store — splits', () => {
  it('splits a pair, advises each hand, and auto-advances on busts', () => {
    const { live } = makeLive()
    live.pick('8')
    live.pick('7')
    live.pick('8')
    expect(live.advice.value?.action).toBe('split')
    live.splitHand()
    expect(live.hands.value).toEqual([['8'], ['8']])
    expect(live.activeHand.value).toBe(0)
    expect(live.nextNeeded.value).toBe('mine')
    // hand 1: 8,T = 18 → stand; then another T busts it onward
    live.pick('T')
    expect(live.advice.value?.action).toBe('stand')
    live.pick('T')
    expect(live.activeHand.value).toBe(1)
    expect(live.activeCards.value).toEqual(['8'])
    expect(live.handState.value).toBe('entry')
    // hand 2: 8,6 = 14 v 7 → hit; the K busts the last hand into round-over
    live.pick('6')
    expect(live.advice.value?.action).toBe('hit')
    live.pick('K')
    expect(live.roundDone.value).toBe(true)
    expect(live.handState.value).toBe('roundDone')
    expect(live.nextNeeded.value).toBe('none')
    expect(live.seen.value).toEqual(['8', '7', '8', 'T', 'T', '6', 'K'])
    live.undo()
    expect(live.roundDone.value).toBe(false)
    expect(live.handState.value).toBe('bust')
    live.undo()
    expect(live.activeCards.value).toEqual(['8', '6'])
    expect(live.advice.value?.action).toBe('hit')
    expect(live.seen.value).toEqual(['8', '7', '8', 'T', 'T', '6'])
  })

  it('resplits up to the table max, then plays the total', () => {
    const { live } = makeLive()
    live.pick('8')
    live.pick('6')
    live.pick('8')
    live.splitHand()
    live.pick('8')
    expect(live.advice.value?.action).toBe('split')
    live.splitHand()
    expect(live.hands.value).toEqual([['8'], ['8'], ['8']])
    live.pick('8')
    expect(live.advice.value?.action).toBe('split')
    live.splitHand()
    expect(live.hands.value).toEqual([['8'], ['8'], ['8'], ['8']])
    // max hands reached: 8,8 plays as hard 16 v 6
    live.pick('8')
    expect(live.advice.value?.action).toBe('stand')
    expect(live.hands.value.length).toBe(4)
  })

  it('gives split aces one card by default', () => {
    const { live } = makeLive()
    live.pick('A')
    live.pick('6')
    live.pick('A')
    expect(live.advice.value?.action).toBe('split')
    live.splitHand()
    live.pick('5')
    // A,5 with the one-card rule — no decision, straight to the next hand
    expect(live.activeHand.value).toBe(1)
    live.pick('K')
    // A,K = 21 — the last hand finishes the round
    expect(live.roundDone.value).toBe(true)
    // rewind the whole finish by hand
    live.undo()
    expect(live.roundDone.value).toBe(false)
    expect(live.handState.value).toBe('twentyone')
    live.undo()
    expect(live.activeCards.value).toEqual(['A'])
    live.undo()
    expect(live.activeHand.value).toBe(0)
    expect(live.activeCards.value).toEqual(['A', '5'])
    expect(live.handState.value).toBe('acesDone')
    expect(live.advice.value).toBeNull()
    // the split survives every undo; hand 1 keeps its earned cards
    expect(live.hands.value).toEqual([['A', '5'], ['A']])
  })

  it('plays split aces out when the table allows drawing', () => {
    const { settings, live } = makeLive()
    settings.updateRules({ splitAcesOneCard: false })
    live.pick('A')
    live.pick('6')
    live.pick('A')
    live.splitHand()
    live.pick('5')
    expect(live.handState.value).toBe('playing')
    // A,5 v 6 with DAS → double
    expect(live.advice.value?.action).toBe('double')
    live.pick('2')
    // A,5,2 = soft 18 v 6 → stand
    expect(live.advice.value?.action).toBe('stand')
    live.undo()
    live.undo()
    // resplit aces off: A,A plays as the no-resplit ace hand → double vs 6
    live.pick('A')
    expect(live.advice.value?.action).toBe('double')
    settings.updateRules({ resplitAces: true })
    expect(live.advice.value?.action).toBe('split')
    live.splitHand()
    expect(live.hands.value.length).toBe(3)
  })
})

describe('live store — undo', () => {
  it('steps back the newest tap: player card, then upcard', () => {
    const { live } = makeLive()
    live.undo()
    expect(live.hands.value).toEqual([[]])
    expect(live.dealer.value).toBeNull()
    live.pick('T')
    live.pick('6')
    live.pick('9')
    live.undo()
    expect(live.activeCards.value).toEqual(['T'])
    expect(live.dealer.value).toBe('6')
    expect(live.seen.value).toEqual(['T', '6'])
    expect(live.nextNeeded.value).toBe('mine')
    live.undo()
    // hand empty again but the upcard is still there — undo reaches it
    expect(live.canUndo.value).toBe(true)
    expect(live.activeCards.value).toEqual([])
    expect(live.seen.value).toEqual(['T'])
    expect(live.dealer.value).toBe('6')
    live.undo()
    expect(live.dealer.value).toBeNull()
    expect(live.seen.value).toEqual([])
    expect(live.nextNeeded.value).toBe('mine')
    expect(live.canUndo.value).toBe(false)
  })

  it('rewinds through split hands without breaking the split', () => {
    const { live } = makeLive()
    live.pick('8')
    live.pick('7')
    live.pick('8')
    live.splitHand()
    live.pick('5')
    live.pick('4')
    live.advance()
    // the active hand awaits its card while hand one's play still holds removable cards
    expect(live.canUndo.value).toBe(true)
    live.undo()
    // hand 2 is at its base — undo rewinds to hand 1 instead
    expect(live.activeHand.value).toBe(0)
    live.undo()
    expect(live.activeCards.value).toEqual(['8', '5'])
    expect(live.seen.value).toEqual(['8', '7', '8', '5'])
    expect(live.advice.value?.action).toBe('hit')
    live.undo()
    expect(live.activeCards.value).toEqual(['8'])
    expect(live.hands.value).toEqual([['8'], ['8']])
    // only load-bearing split cards remain — undo is exhausted
    expect(live.canUndo.value).toBe(false)
  })
})

describe('live store — counting', () => {
  it('shows an insurance row only against an ace, count off by default', () => {
    const { live } = makeLive()
    live.pick('4')
    live.pick('9')
    expect(live.insurance.value).toBeNull()
    expect(live.count.value).toBeNull()
    live.undo()
    live.undo()
    live.pick('4')
    live.pick('A')
    expect(live.insurance.value?.take).toBe(false)
    expect(live.insurance.value?.label).toBe('Decline insurance')
  })

  it('takes insurance when the counted true count is high', () => {
    const { settings, live } = makeLive()
    settings.updateRules({ decks: 1 })
    for (let round = 0; round < 13; round++) {
      live.pick('6')
      live.pick('6')
      live.newRound()
    }
    settings.updatePractice({ counting: true })
    live.pick('4')
    live.pick('A')
    // 26 sixes logged: +26 running, 24 cards left → TC far past +3
    expect(live.seen.value).toHaveLength(28)
    expect(live.count.value?.running).toBe(26)
    expect(live.count.value?.trueCount).toBeCloseTo(52, 5)
    expect(live.count.value?.remainingDecks).toBeCloseTo(24 / 52, 5)
    expect(live.insurance.value?.take).toBe(true)
    expect(live.insurance.value?.label).toBe('Take insurance')
  })
})

describe('live store — resets', () => {
  it('new round keeps the count log; new shoe clears everything', () => {
    const { live } = makeLive()
    live.pick('T')
    live.pick('T')
    live.pick('6')
    live.newRound()
    expect(live.hands.value).toEqual([[]])
    expect(live.dealer.value).toBeNull()
    expect(live.seen.value).toEqual(['T', 'T', '6'])
    expect(live.handState.value).toBe('entry')
    expect(live.advice.value).toBeNull()
    expect(live.canUndo.value).toBe(false)
    // a fresh hand still counts: the log only clears on a shoe reset
    live.pick('5')
    live.pick('9')
    expect(live.seen.value).toEqual(['T', 'T', '6', '5', '9'])
    live.newShoe()
    expect(live.hands.value).toEqual([[]])
    expect(live.seen.value).toEqual([])
    expect(live.nextNeeded.value).toBe('mine')
  })
})
